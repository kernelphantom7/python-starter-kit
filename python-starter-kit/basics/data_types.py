"""
data_types.py
--------------
Examples of Python's core data types.
"""

# String
greeting = "Hello, Python!"

# Integer
count = 10

# Float
price = 19.99

# Boolean
is_active = False

# List
fruits = ["apple", "banana", "orange"]

# Tuple
coordinates = (10, 20)

# Dictionary
person = {"name": "Jeremie", "level": "beginner"}

print(type(greeting), greeting)
print(type(count), count)
print(type(price), price)
print(type(is_active), is_active)
print(type(fruits), fruits)
print(type(coordinates), coordinates)
print(type(person), person)
